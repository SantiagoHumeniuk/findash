// Bundles the asset builder for the yahoo-finance-proxy Edge Function, so the
// browser and the server keep using one implementation.
// Run: npm run build:asset-builder

import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

export async function bundleAssetBuilder() {
  const result = await build({
    entryPoints: [fileURLToPath(new URL('../src/services/api/yahoo-asset-builder.ts', import.meta.url))],
    bundle: true,
    format: 'esm',
    target: 'es2022',
    write: false,
    logLevel: 'silent',
    banner: { js: '// @ts-nocheck\n// Generated by scripts/build-asset-builder.mjs. Do not edit.' },
  });
  return result.outputFiles[0].text.replace(/\r\n/g, '\n');
}

if (process.argv[1]?.endsWith('build-asset-builder.mjs')) {
  const { writeFileSync } = await import('node:fs');
  const target = new URL('../supabase/functions/yahoo-finance-proxy/asset-builder.generated.js', import.meta.url);
  writeFileSync(target, await bundleAssetBuilder());
  console.log('asset-builder.generated.js actualizado.');
}
